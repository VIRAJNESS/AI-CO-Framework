"""Report generation service — DOCX (python-docx), PPTX (python-pptx) and
PDF (ReportLab). WeasyPrint is available for HTML->PDF when richer layout is
needed later; ReportLab keeps Step 1 dependency-light at runtime.

Generated artifacts are persisted through the StorageProvider port, so the
same code writes to local disk, MinIO/S3, Azure Blob or GCS based solely on
the STORAGE_PROVIDER environment variable.
"""

from __future__ import annotations

import io
from datetime import datetime, timezone

from docx import Document
from pptx import Presentation
from pptx.util import Inches
from reportlab.lib.pagesizes import A4
from reportlab.pdfgen import canvas

from app.providers.storage import StorageProvider

_SUPPORTED_FORMATS = {"docx", "pptx", "pdf"}


def generate_report(
    storage: StorageProvider,
    title: str,
    summary: str,
    fmt: str,
) -> dict:
    """Render an engagement report in the requested format and persist it.

    Returns the storage key and locator. Raises ValueError on unknown format.
    """
    fmt = fmt.lower()
    if fmt not in _SUPPORTED_FORMATS:
        raise ValueError(f"Unsupported format '{fmt}'. Supported: {sorted(_SUPPORTED_FORMATS)}")
    if not title.strip():
        raise ValueError("Report title must not be empty")

    timestamp = datetime.now(timezone.utc).strftime("%Y%m%dT%H%M%SZ")
    key = f"reports/{timestamp}-{_slug(title)}.{fmt}"

    renderers = {"docx": _render_docx, "pptx": _render_pptx, "pdf": _render_pdf}
    data, content_type = renderers[fmt](title, summary)

    locator = storage.put(key, data, content_type)
    return {"key": key, "locator": locator, "format": fmt, "size_bytes": len(data)}


def _slug(text: str) -> str:
    """Filesystem/URL-safe slug from a title."""
    return "".join(c.lower() if c.isalnum() else "-" for c in text).strip("-")[:60]


def _render_docx(title: str, summary: str) -> tuple[bytes, str]:
    doc = Document()
    doc.add_heading(title, level=0)
    doc.add_paragraph(summary)
    doc.add_paragraph(f"Generated by AI Coach Mastery at {datetime.now(timezone.utc).isoformat()}")
    buffer = io.BytesIO()
    doc.save(buffer)
    return buffer.getvalue(), (
        "application/vnd.openxmlformats-officedocument.wordprocessingml.document"
    )


def _render_pptx(title: str, summary: str) -> tuple[bytes, str]:
    presentation = Presentation()
    slide = presentation.slides.add_slide(presentation.slide_layouts[0])  # title layout
    slide.shapes.title.text = title
    slide.placeholders[1].text = summary[:300]
    body_slide = presentation.slides.add_slide(presentation.slide_layouts[5])  # blank-ish
    textbox = body_slide.shapes.add_textbox(Inches(0.5), Inches(0.5), Inches(9), Inches(5))
    textbox.text_frame.text = summary
    buffer = io.BytesIO()
    presentation.save(buffer)
    return buffer.getvalue(), (
        "application/vnd.openxmlformats-officedocument.presentationml.presentation"
    )


def _render_pdf(title: str, summary: str) -> tuple[bytes, str]:
    buffer = io.BytesIO()
    pdf = canvas.Canvas(buffer, pagesize=A4)
    width, height = A4
    pdf.setFont("Helvetica-Bold", 18)
    pdf.drawString(50, height - 70, title[:80])
    pdf.setFont("Helvetica", 11)
    # Simple word-wrap for the summary body.
    y = height - 110
    for line in _wrap(summary, 90):
        if y < 60:
            pdf.showPage()
            pdf.setFont("Helvetica", 11)
            y = height - 70
        pdf.drawString(50, y, line)
        y -= 16
    pdf.save()
    return buffer.getvalue(), "application/pdf"


def _wrap(text: str, width: int) -> list[str]:
    """Greedy word wrap preserving words."""
    words, lines, current = text.split(), [], ""
    for word in words:
        candidate = f"{current} {word}".strip()
        if len(candidate) <= width:
            current = candidate
        else:
            lines.append(current)
            current = word
    if current:
        lines.append(current)
    return lines or [""]
